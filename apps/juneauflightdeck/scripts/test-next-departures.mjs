import assert from 'node:assert/strict';
import { parseCalendarDepartures, sortDepartures, juneauDate } from '../lib/nextDepartures.ts';
const tour = { id: 'test', title: 'Glacier tour', supplierName: 'Operator', directOperatorHref: 'https://fareharbor.com/embeds/book/temscoair-juneau/items/214803/?ref=juneauflightdeck&asn=welcometoalaskatours&full_items=yes' };
const now = new Date('2027-06-15T16:00:00Z');
const slot = { pk: -42, item: { pk: 214803, name: 'Glacier walk', minimum_initial_party_size: 1 }, utc_start_at: '2027-06-15T20:45:00+0000', is_bookable: true, approximate_available_capacity: 0 };
const parse = (change = {}, date = '2027-06-15', after = '00:00', pax = 2) => parseCalendarDepartures({ availabilities: [{ ...slot, ...change }] }, tour, date, after, pax, now);
assert.equal(parse()[0].timeLabel, '12:45 PM AKDT');
assert.equal(parse()[0].startsAt, '2027-06-15T20:45:00.000Z');
const url = new URL(parse()[0].bookingUrl);
assert.equal(url.searchParams.get('availability'), '-42');
assert.equal(url.searchParams.get('asn'), 'welcometoalaskatours');
assert.equal(url.searchParams.get('ref'), 'juneauflightdeck');
for (const flag of ['is_sold_out', 'is_waitlist', 'is_unlisted', 'is_bookable_only_by_phone', 'is_past_cutoff_with_bookings', 'is_past_cutoff_without_bookings']) assert.equal(parse({ [flag]: true }).length, 0, flag);
assert.equal(parse({ is_bookable: false }).length, 0);
assert.equal(parse({ is_bookable: undefined }).length, 0);
assert.equal(parse({ booking_restriction: 'closed' }).length, 0);
assert.equal(parse({ utc_start_at: '2027-06-15T15:00:00Z' }).length, 0);
assert.equal(parse({}, '2027-06-16').length, 0);
assert.equal(parse({}, '2027-06-15', '13:00').length, 0);
assert.equal(parse({ utc_start_at: undefined, start_at: '2027-06-15T12:45:00' }).length, 0);
assert.equal(parse({ item: { pk: 99 } }).length, 0);
assert.equal(parse({ item: { pk: 214803, maximum_initial_party_size: 1 } }).length, 0);
assert.equal(parse({ item: { pk: 214803, minimum_initial_party_size: 3 } }).length, 0);
assert.throws(() => parseCalendarDepartures({}, tour, '2027-06-15', '00:00', 2, now));
assert.equal(juneauDate(new Date('2027-06-16T02:00:00Z')), '2027-06-15');
assert.equal(parse({ utc_start_at: '2027-06-15T12:45:00-08:00' })[0].timeLabel, '12:45 PM AKDT');
const later = { ...parse()[0], id: 'later', startsAt: '2027-06-15T22:00:00Z' };
assert.deepEqual(sortDepartures([later, ...parse(), ...parse()]).map(d => d.id), ['test--42', 'later']);
console.log('Departure selection, cutoffs, timezone, party limits, failure, sorting and attribution assertions passed.');

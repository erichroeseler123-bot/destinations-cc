export function getDccCanonicalHostedCatalogSnapshot(options?: {
  theme?: HostedCruiseThemeSlug | null;
  organizerSlug?: string | null;
  includeHeld?: boolean;
}): CanonicalHostedCatalogSnapshot {
  const includeHeld = options?.includeHeld ?? true;
  const orgFilter = options?.organizerSlug?.trim().toLowerCase() || "";
  const themeFilter = options?.theme || null;

  let sailings = DCC_CANONICAL_HOSTED_SAILINGS.filter((s) =>
    includeHeld ? true : !s.scheduleHoldReason,
  );

  if (orgFilter) {
    const matchedOrg = resolveDccHostedOrganizerBySlugOrAlias(orgFilter);
    const canonicalSlug = matchedOrg ? matchedOrg.organizerSlug : orgFilter;
    sailings = sailings.filter((s) => s.organizerSlug === canonicalSlug);
  }

  if (themeFilter) {
    sailings = sailings.filter(
      (s) => s.primaryTheme === themeFilter || s.secondaryThemes.includes(themeFilter),
    );
  }

  const activeOrgSlugs = new Set(sailings.map((s) => s.organizerSlug));
  const organizersList =
    orgFilter || themeFilter
      ? DCC_CANONICAL_HOSTED_ORGANIZERS.filter((o) => activeOrgSlugs.has(o.organizerSlug))
      : DCC_CANONICAL_HOSTED_ORGANIZERS;

  return {
    contractVersion: CANONICAL_HOSTED_CRUISE_CONTRACT_VERSION,
    snapshotId: DCC_HOSTED_CATALOG_SNAPSHOT_ID,
    generatedAt: DCC_HOSTED_CATALOG_GENERATED_AT,
    owner: "dcc",
    consumerCanonicalHost: "https://cruisepromenade.com",
    themes: HOSTED_CRUISE_THEMES,
    organizers: organizersList,
    hostedSailings: sailings,
    recentChangeEvents: DCC_RECENT_CATALOG_CHANGE_EVENTS,
  };
}

export function resolveDccHostedOrganizerBySlugOrAlias(
  slugOrAlias: string,
): CanonicalHostedOrganizerFactRecord | null {
  const clean = slugOrAlias.trim().toLowerCase();
  if (!clean) return null;
  return (
    DCC_CANONICAL_HOSTED_ORGANIZERS.find(
      (o) =>
        o.organizerSlug === clean ||
        o.aliases.some((a) => a.toLowerCase() === clean),
    ) ?? null
  );
}

export function validateDccHostedCatalogIntegrity() {
  return validateHostedCruiseRedundancySafeguards({
    organizers: DCC_CANONICAL_HOSTED_ORGANIZERS,
    hostedSailings: DCC_CANONICAL_HOSTED_SAILINGS as ReadonlyArray<
      CanonicalHostedSailingFactRecord & Record<string, unknown>
    >,
    dccConsumerCanonicalUrls: [],
  });
}

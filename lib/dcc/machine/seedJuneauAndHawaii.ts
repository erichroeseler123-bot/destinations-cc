function makeEntity(params: {
  id: string;
  entityType: MachineEntity["entityType"];
  canonicalName: string;
  jurisdiction: string | null;
  geographicScope: GeographicScope;
  attributes?: Record<string, unknown>;
  connectedIds?: string[];
}): MachineEntity {
  const version = "1.0.0";
  const core = {
    objectType: "Entity" as const,
    id: params.id,
    version,
    entityType: params.entityType,
    canonicalName: params.canonicalName,
    jurisdiction: params.jurisdiction,
    geographicScope: params.geographicScope,
    status: "verified" as const,
    valid_from: "2026-01-01T00:00:00.000Z",
    valid_to: "2027-12-31T23:59:59.000Z",
    observed_at: "2026-04-12T00:00:00.000Z",
    retrieved_at: "2026-04-12T00:00:00.000Z",
    attributes: params.attributes ?? {},
    connectedIds: params.connectedIds ?? [],
    stableReferenceUri: `/r/${params.id}`,
    immutableReferenceUri: `/r/${params.id}/v/${version}`,
  };
  return {
    ...core,
    contentHash: hashCanonicalJson(core),
  };
}

function makeSourceBundle(params: {
  sourceId: string;
  title: string;
  organization: string;
  authorityTier: MachineSource["authorityTier"];
  canonicalUrl: string;
  jurisdiction: string;
  retrievalMethod: string;
  licenseOrReuseStatus: string;
  retrievedAt: string;
  validFrom: string;
  validTo: string;
  snapshotPayload: Record<string, unknown>;
  fragments: Array<{
    fragmentId: string;
    locator: string;
    verbatimExcerpt: string;
    structuredFieldPath: string;
    structuredValue: unknown;
  }>;
}): {
  source: MachineSource;
  snapshot: MachineSourceSnapshot;
  fragments: MachineEvidenceFragment[];
} {
  const version = "1.0.0";
  const snapshotId = `snap:${params.sourceId.replace(/^src:/, "")}:v1`;
  const snapshotContent = canonicalJsonStringify({
    sourceId: params.sourceId,
    canonicalUrl: params.canonicalUrl,
    retrievedAt: params.retrievedAt,
    payload: params.snapshotPayload,
  });

  const storedArtifact = writeImmutableArtifact({
    category: "sources",
    filename: `${snapshotId.replace(/:/g, "_")}.json`,
    content: snapshotContent,
  });

  const snapshot: MachineSourceSnapshot = {
    objectType: "SourceSnapshot",
    id: snapshotId,
    sourceId: params.sourceId,
    version,
    canonicalUrl: params.canonicalUrl,
    retrieved_at: params.retrievedAt,
    observed_at: params.retrievedAt,
    valid_from: params.validFrom,
    valid_to: params.validTo,
    httpStatus: 200,
    contentType: "application/json",
    retrievalMethod: params.retrievalMethod,
    licenseOrReuseStatus: params.licenseOrReuseStatus,
    artifactStorageUri: storedArtifact.storageUri,
    contentHash: storedArtifact.sha256,
    byteLength: storedArtifact.byteLength,
    status: "verified",
    provenanceOrigin: "curated_seed_fixture",
    stableReferenceUri: `/r/${snapshotId}`,
    immutableReferenceUri: `/r/${snapshotId}/v/${version}`,
  };

  const sourceCore = {
    objectType: "Source" as const,
    id: params.sourceId,
    version,
    title: params.title,
    organization: params.organization,
    authorityTier: params.authorityTier,
    canonicalUrl: params.canonicalUrl,
    jurisdiction: params.jurisdiction,
    retrievalMethod: params.retrievalMethod,
    licenseOrReuseStatus: params.licenseOrReuseStatus,
    status: "verified" as const,
    provenanceOrigin: "curated_seed_fixture" as const,
    latestSnapshotId: snapshotId,
    valid_from: params.validFrom,
    valid_to: params.validTo,
    observed_at: params.retrievedAt,
    retrieved_at: params.retrievedAt,
    stableReferenceUri: `/r/${params.sourceId}`,
    immutableReferenceUri: `/r/${params.sourceId}/v/${version}`,
  };

  const source: MachineSource = {
    ...sourceCore,
    contentHash: hashCanonicalJson(sourceCore),
  };

  const fragments: MachineEvidenceFragment[] = params.fragments.map((f) => {
    const fragCore = {
      objectType: "EvidenceFragment" as const,
      id: f.fragmentId,
      sourceId: params.sourceId,
      snapshotId,
      version,
      locator: f.locator,
      excerptOrStructuredField: {
        verbatimExcerpt: f.verbatimExcerpt,
        structuredFieldPath: f.structuredFieldPath,
        structuredValue: f.structuredValue,
      },
      observed_at: params.retrievedAt,
      retrieved_at: params.retrievedAt,
      valid_from: params.validFrom,
      valid_to: params.validTo,
      status: "verified" as const,
      provenanceOrigin: "curated_seed_fixture" as const,
      stableReferenceUri: `/r/${f.fragmentId}`,
      immutableReferenceUri: `/r/${f.fragmentId}/v/${version}`,
    };
    return {
      ...fragCore,
      contentHash: hashCanonicalJson(fragCore),
    };
  });

  return { source, snapshot, fragments };
}

function makeClaimAndVersion(params: {
  claimId: string;
  versionNumber?: number;
  epistemicKind?: MachineClaim["epistemicKind"];
  subject: string;
  predicate: string;
  typedValue: TypedClaimValue;
  unitOrCurrency: string | null;
  geographicScope: GeographicScope;
  jurisdiction: string;
  validFrom: string;
  validTo: string;
  source: MachineSource;
  snapshot: MachineSourceSnapshot;
  fragment: MachineEvidenceFragment;
}): { claim: MachineClaim; claimVersion: MachineClaimVersion } {
  const versionNumber = params.versionNumber ?? 1;
  const versionId = `${params.claimId.replace(/^clm:/, "clmv:")}:v${versionNumber}`;
  const epistemicKind = params.epistemicKind ?? "fact";

  const claimVersionCore = {
    objectType: "ClaimVersion" as const,
    claimId: params.claimId,
    versionId,
    versionNumber,
    epistemicKind,
    subject: params.subject,
    predicate: params.predicate,
    typedValue: params.typedValue,
    unitOrCurrency: params.unitOrCurrency,
    geographicScope: params.geographicScope,
    jurisdiction: params.jurisdiction,
    valid_from: params.validFrom,
    valid_to: params.validTo,
    observed_at: params.source.observed_at,
    retrieved_at: params.source.retrieved_at,
    known_from: params.source.retrieved_at,
    known_to: null,
    status: "verified" as const,
    provenanceOrigin: "curated_seed_fixture" as const,
    sourceId: params.source.id,
    sourceOrganization: params.source.organization,
    canonicalSourceUrl: params.source.canonicalUrl,
    sourceSnapshotId: params.snapshot.id,
    evidenceFragmentId: params.fragment.id,
    supportingFragment: {
      locator: params.fragment.locator,
      verbatimExcerpt: params.fragment.excerptOrStructuredField.verbatimExcerpt,
      structuredFieldPath: params.fragment.excerptOrStructuredField.structuredFieldPath,
      structuredValue: params.fragment.excerptOrStructuredField.structuredValue,
    },
    retrievalMethod: params.source.retrievalMethod,
    licenseOrReuseStatus: params.source.licenseOrReuseStatus,
    supersededByVersionId: null,
    supersedesVersionId: null,
    retractionId: null,
    withdrawalInfo: null,
    conflictingClaimVersionIds: [],
    verificationApprovedBy: "dcc-evidence-board@destinationcommandcenter.com",
    stableReferenceUri: `/r/${params.claimId}`,
    immutableReferenceUri: `/r/${params.claimId}/v/${versionId}`,
  };

  const claimVersion: MachineClaimVersion = {
    ...claimVersionCore,
    evidenceHash: hashCanonicalJson(claimVersionCore),
  };

  const claim: MachineClaim = {
    objectType: "Claim",
    id: params.claimId,
    currentVersionId: versionId,
    subjectId: params.subject,
    predicate: params.predicate,
    epistemicKind,
    status: "verified",
    hasOpenConflict: false,
    versionHistoryIds: [versionId],
    currentVersion: claimVersion,
    stableReferenceUri: `/r/${params.claimId}`,
    immutableReferenceUri: `/r/${params.claimId}/v/${versionId}`,
  };

  return { claim, claimVersion };
}

